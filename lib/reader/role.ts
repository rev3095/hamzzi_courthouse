// 피해자로 조사받는 경우는 받는 쪽이 아니다
const VICTIM_INTERVIEW = /피해자(로|조사|진술)|참고인/;
const SUED =
  /민사(가|를|소송이|소송을)?(들어왔|들어옴|걸려|걸었대|걸어왔)|(소장|지급명령|이행권고결정|변론기일통지|소송서류|법원(에서)?(서류|우편|등기))(정본)?(이|을|를)?(받|왔|송달|날아|도착)|소송(을)?당|민사소송(이)?(들어|걸려)|피소|(저를|나를)상대로(소송|소|청구|손해배상)|청구(를)?당|제가피고|피고(가|로)(됐|되)|손해배상(을)?청구한다고|소송(을)?걸겠다/;
// 갚을 쪽 낱말 가운데 묻는 사람이 갚을 쪽임이 문장 자체로 드러나는 것만. 상대의 요구를 전하는 꼴("갚으라고 하는데")은
// 내가 요구하는 문장과 헷갈려 아래 relayedDemand의 조건을 거친다 (2026-11-20 legal-reviewer 검토)
const OWES =
  /갚아야하|안갚아도|빌린돈|(돈을|제가)?빌렸(는데|어|어요)|못갚|갚고있|갚으면되|세입자(에게|한테)(보증금|돌려)|세입자가(안나|나가지|보증금을달)|직원이(퇴직금|월급|임금|수당)?(을|를)?달라|직원(에게|한테)(줘야|월급|퇴직금)|직원을해고|해고하려|해고해도되|(제가|저는)(집주인|임대인|사장|사업주|매도인|가해자)/;
// 받을 쪽 표현이 함께 있으면 갚을 쪽으로 보지 않는다 (빌려준 돈을 못 받음)
const CREDITOR = /빌려준|빌려줬|돌려받|못받|안받|받을수있|받아야|안돌려|안줘|안준|안주/;

// 묻는 사람이 소송을 건 쪽이면 소장 낱말이 있어도 서류를 받은 쪽이 아니다
const PLAINTIFF =
  /(제가|내가|저희가|저도|나도).{0,12}(민사|소송|소)(를|을)?(걸|제기|냈|넣|진행)|민사걸고|소송하래서/;
const AGAINST_ME = /(저를|나를|저희를)상대로/;

/** 입장 판별. 여러 신호가 겹치면 받는 쪽(수사 → 서류 → 갚을 쪽) 순서로 본다 */
export const isPlaintiff = (text: string) => PLAINTIFF.test(text) && !AGAINST_ME.test(text);

// 상대의 요구를 전하는 꼴 ("세입자가 보증금 돌려달라고 하는데", "친구가 빌려준 돈 갚으라고 난리", "직원이 퇴직금 달래요").
// 이 신호로 묻는 사람을 갚을 쪽으로 돌리면 그 사람에게는 절차 순서 대신 범위 밖 안내가 나간다. 잘못 돌리면
// 피해자·요구하는 쪽이 필요한 절차를 못 보게 되므로, 아래 조건을 모두 갖췄을 때만 센다 (2026-11-20 legal-reviewer 두 차례 검토 반영).
// 놓치면 이전처럼 요구하는 쪽 절차가 보일 뿐이라, 애매하면 세지 않는 쪽을 고른다.
//   ① 요구하는 말 + 지금 전하는 끝말 ("…라고 하는데", "…라는데", "…래요"). 지난 일("달라고 했어요")·"-며/-면서"는 넣지 않는다
//   ② 요구하는 말 바로 앞에 돈 낱말 (보증금·퇴직금·양육비·…원 등) — "만나 달라", "용서해 주라", "진단서 내라"를 거른다.
//      돈 낱말 바로 앞이 '-ㄴ' 꼴 행위("횡령한 돈", "쓴 돈", "밀린 월세")면 그 행위의 주인이 갚을 쪽일 수 있어 세지 않는다 ("준 돈"은 센다)
//   ③ 요구하는 말과 **같은 절**에 다른 사람이 주어로 있다. 주어와 요구하는 말 사이에 절이 끊기는 말(-는데·-서·-니까·지난 일 등)이 있으면
//      그 주어는 다른 일의 주어다 ("회사에서 일했는데 월급 달라고 하는데"). 주어가 없거나 "제가"면 내가 요구한 것일 수 있다
//   ④ 받을 사람(…에게·한테·께·회사에·보고)이 앞에 있으면 내가 요구하는 문장이다. 단 "저한테"처럼 나를 가리키면 상대의 요구다
//   ⑤ 범죄 피해(협박·피싱·사기·횡령·폭행·스토킹), 처분(과태료·세금·환수) 낱말이 있으면 보지 않는다 (그 사람의 절차가 따로 있다)
const SAY_STEM =
  "(?:돌려달라|갚아달라|(?<![어아여워와해줘려며봐서나내쳐꿔빼춰가써])달라|갚으라|갚아라|내놓으라|내놓아라|물어내라|물어달라|(?:변상|배상|반환|지급|변제|상환)하라|(?:변상|배상|반환|지급)해달라|(?<![보어아여워와해줘려며봐서])내라|(?<![어아여워와해줘려며봐서나내쳐꿔빼춰가써])주라)";
const SAY_END =
  "(?:고(?:하는데|해요|하네|한대|하더라|하잖|난리|그래요|그러네|그런다|그러는데|독촉|요구해요|요구하는데|연락와|문자와|전화와|하고있)|는데)";
const SHORT = "(?:갚으래|내놓으래|물어내래|변상하래|배상하래|달래)(?:요|는데|네)";
const RELAYED_DEMAND = new RegExp(`${SAY_STEM}${SAY_END}|${SHORT}`, "g");
const MONEY_BEFORE =
  /(돈|보증금|전세금|퇴직금|월급|임금|급여|수당|양육비|합의금|위약금|물건값|대금|수리비|치료비|변상금|배상금|빚|대출금|잔금|계약금|월세|관리비|공사비|비용|금액|\d+(?:만|천|억)?원)(?:을|를|이랑|까지|도|만|좀|부터)?(?:다|전부|모두|빨리|당장|지금|바로)*(?:돌려)?$/;
// 가리기가 남긴 이름 자리는 §로 바꿔 본다 (`세입자이름1`이 '세입자이'로 읽히지 않게). 주격 조사가 붙고 자기소개가 아닐 때만 주어다
const OTHER_SUBJECT =
  /(?:세입자|임차인|집주인|임대인|건물주|직원|알바생?|채권자|친구|지인|거래처|상대방?|전처|전남편|전남친|전여친|가해자|업체|회사|사장님?|손님|고객|이웃|옆집|윗집|아랫집|매수인|매도인|카드사|은행|대부업체|추심업체|보험사|그쪽|그사람|걔|쟤|씨)(?:이|가|께서|쪽에서|측에서|에서)|(?<!은|이름|성명|저|제)§(?:씨)?(?:이|가|께서)/g;
const FIRST_PERSON = /(?:제가|저는|내가|나는|저희가|저도|나도)/;
// 맨 '에'는 "예전에", "작년에"와 겹쳐 기관·사람 낱말 뒤일 때만 받는 사람으로 본다
const TO_SOMEONE =
  /(?:(?<![가-힣])(?:저|나|제|저희)(?:에게|한테|께|보고|더러))|((?:에게|한테|께|보고|더러)|(?:회사|은행|보험사|가게|업체|집주인|건물주|임대인|사장님?|상대방?|구청|시청|학교|병원|쇼핑몰|판매자)(?:쪽)?에(?!서))/g;
// 같은 절이 아니라는 표시: 이어 주는 말(-는데·-서·-니까·-다가·-더니·뒤·후) (따옴 말 "-다고/-다며"는 같은 사람의 말이라 미리 뺀다)
const CLAUSE_BREAK = /는데|(?<!에)서|니까|으니|다가|더니|자니|라서|면서|며|뒤|후에|하고/;
const SKIP =
  /협박|공갈|피싱|스미싱|몸캠|사기|횡령|절도|훔쳐|훔친|폭행|때리|때려|때렸|맞았|스토킹|찾아와|따라다|과태료|범칙금|세금|세무서|국세|지방세|가산세|환수|부정수급|과징금|이행강제금|건강보험료|국민연금|고지서/;

/** 받침 번호 (0 = 없음, 4 = ㄴ, 20 = ㅆ) */
const jong = (ch: string) => {
  const c = ch.charCodeAt(0) - 0xac00;
  return c >= 0 && c < 11172 ? c % 28 : 0;
};

/** 주어와 요구하는 말 사이가 같은 절인지 (지난 일 받침 ㅆ, 이어 주는 말이 없음) */
function sameClause(between: string): boolean {
  const s = between.replace(/[가-힣]다(?:고|며|면서)/g, "");
  if (CLAUSE_BREAK.test(s)) return false;
  return ![...s].some((ch) => jong(ch) === 20);
}

/** 상대가 나에게 돈을 요구한다고 전하는 문장인지 (조건은 위 ①~⑤) */
export function relayedDemand(raw: string): boolean {
  if (SKIP.test(raw)) return false;
  const text = raw.replace(/이름\d+/g, "§");
  for (const m of text.matchAll(RELAYED_DEMAND)) {
    const at = m.index ?? 0;
    const before = text.slice(Math.max(0, at - 30), at);
    const money = before.match(MONEY_BEFORE);
    if (!money || money.index === undefined) continue;
    // ② 돈 낱말 바로 앞 '-ㄴ' 행위 (준·빌려준은 센다)
    const prev = before[money.index - 1] ?? "";
    if (jong(prev) === 4 && prev !== "준") continue;
    // ③ 같은 절의 마지막 다른 사람 주어
    const subjects = [...before.matchAll(OTHER_SUBJECT)];
    const last = subjects[subjects.length - 1];
    if (!last || last.index === undefined) continue;
    const between = before.slice(last.index + last[0].length, at);
    if (!sameClause(between) || FIRST_PERSON.test(between)) continue;
    // ④ 주어 뒤에 받을 사람이 있으면 내가 요구하는 문장 (나를 가리키는 받는 사람은 상대의 요구라 괜찮다)
    if ([...between.matchAll(TO_SOMEONE)].some((t) => t[1] !== undefined)) continue;
    return true;
  }
  return false;
}

// 상대의 요구를 전하는 문장에서도 받을 쪽으로 볼 표현 (빌려준 돈은 상대가 빌려준 것일 수 있어 여기서는 보지 않는다)
const CREDITOR_STRICT = /돌려받|못받|안받|받아야|안돌려|안줘|안준|안주/;

export function detectRole(text: string): Role {
  if (ACCUSED.test(text) && !VICTIM_INTERVIEW.test(text)) return "accused";
  if (SUED.test(text) && !isPlaintiff(text)) return "sued";
  if (OWES.test(text) && !CREDITOR.test(text)) return "owes";
  if (relayedDemand(text) && !CREDITOR_STRICT.test(text)) return "owes";
  return "claimant";
}
