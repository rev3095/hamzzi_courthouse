// 묻는 사람의 입장 (DEC-048) — 순수 규칙. 절차 타임라인은 돈·권리를 요구하는 쪽 기준이라,
// 받는 쪽(수사를 받는 쪽·소송 서류를 받은 쪽·갚아야 하는 쪽)에게 요구하는 쪽 절차를 보이지 않으려고 먼저 가린다.
// 라벨 평가(DEC-045)에서 가장 많이 틀린 유형이 이 입장이라 섹션 점수보다 먼저 본다.
// 누가 잘못했는지·결과가 어떨지는 판단하지 않는다 (절대 규칙 2).

export type Role =
  /** 피해를 입었거나 돈·권리를 요구하는 쪽 (기본) */
  | "claimant"
  /** 고소·신고를 당했거나 수사를 받는 쪽 */
  | "accused"
  /** 소장·지급명령 같은 법원 서류를 받은 쪽 */
  | "sued"
  /** 서류는 없지만 갚거나 돌려줘야 하는 쪽 (빌린 쪽·임대인·사업주) */
  | "owes";

export const ROLE_TEXT: Record<Role, string> = {
  claimant: "피해를 입었거나 무언가를 요구하려는 쪽으로 읽었어요.",
  accused: "고소·신고를 당했거나 수사를 받는 쪽으로 읽었어요.",
  sued: "법원 서류를 받은 쪽으로 읽었어요.",
  owes: "갚거나 돌려줘야 하는 쪽으로 읽었어요.",
};

const ACCUSED =
  /고소(를|가)?(받|들어오|접수)|고소(를)?(하였다는|했다는)(연락|메시지|문자)|(유죄|실형|전과)(판결)?(이)?(나오|받|남)|고소(를)?당|신고(를)?당|고발(을)?당|피의자|피고소인|입건|약식명령|(저를|나를|저도|제가)(고소|신고|고발)(했|하겠|한대|당|됐)|제가(때렸|훔쳤|만졌|찍었|폭행했|욕했)다고|(허위|거짓|억울하게)(로)?(고소|신고)|사고(를)?냈|가해자로(지목|몰)|출석요구|출석하라|조사(를)?(받으래|받으라|받아야|받으러)|경찰서(에서)?(연락|출석|오라|부르)|(군사경찰|군검찰|경찰|검찰)(에)?(넘어|송치|불려)|벌금(형|이)?(나왔|날아|받았)|((저를|나를|저도|나도|오히려|역으로)|(상대(방)?|그쪽|걔|그사람|피해자|가해자)(가|이|쪽에서|도)).{0,15}(고소|신고|고발)(한대|하겠대|하겠다고|한다고|한다네|하겠다네|하겠다며|한다며|했대|했다고)|맞고소|(제가|저는|내가).{0,20}(처벌받|전과|벌금(이|을)?얼마|형량|합의금(을|이)?(요구|달라|물어))/;
// 피해자로 조사받는 경우는 받는 쪽이 아니다
const VICTIM_INTERVIEW = /피해자(로|조사|진술)|참고인/;
const SUED =
  /민사(가|를|소송이|소송을)?(들어왔|들어옴|걸려|걸었대|걸어왔)|(소장|지급명령|이행권고결정|변론기일통지|소송서류|법원(에서)?(서류|우편|등기))(정본)?(이|을|를)?(받|왔|송달|날아|도착)|소송(을)?당|민사소송(이)?(들어|걸려)|피소|(저를|나를)상대로(소송|소|청구|손해배상)|청구(를)?당|제가피고|피고(가|로)(됐|되)|손해배상(을)?청구한다고|소송(을)?걸겠다/;
const OWES =
  /(세입자|직원|알바생|채권자|친구|지인|거래처|상대방)(가|이).{0,30}(달래|달라고해|달라네|갚으래|갚으라|돌려달래|돌려달라네|내놓으래)|갚아야하|안갚아도|갚으래|갚으라는데|갚으라고|돌려달라는데|돌려달래|물어내라|빌린돈|(돈을|제가)?빌렸(는데|어|어요)|못갚|갚고있|갚으면되|세입자(에게|한테)(보증금|돌려)|세입자가(안나|나가지|보증금을달)|직원이(퇴직금|월급|임금|수당)?(을|를)?달라|직원(에게|한테)(줘야|월급|퇴직금)|직원을해고|해고하려|해고해도되|(제가|저는)(집주인|임대인|사장|사업주|매도인|가해자)/;
// 받을 쪽 표현이 함께 있으면 갚을 쪽으로 보지 않는다 (빌려준 돈을 못 받음)
const CREDITOR = /빌려준|빌려줬|돌려받|못받|안받|받을수있|받아야|안돌려|안줘|안준|안주/;

// 묻는 사람이 소송을 건 쪽이면 소장 낱말이 있어도 서류를 받은 쪽이 아니다
const PLAINTIFF =
  /(제가|내가|저희가|저도|나도).{0,12}(민사|소송|소)(를|을)?(걸|제기|냈|넣|진행)|민사걸고|소송하래서/;
const AGAINST_ME = /(저를|나를|저희를)상대로/;

/** 입장 판별. 여러 신호가 겹치면 받는 쪽(수사 → 서류 → 갚을 쪽) 순서로 본다 */
export const isPlaintiff = (text: string) => PLAINTIFF.test(text) && !AGAINST_ME.test(text);

export function detectRole(text: string): Role {
  if (ACCUSED.test(text) && !VICTIM_INTERVIEW.test(text)) return "accused";
  if (SUED.test(text) && !isPlaintiff(text)) return "sued";
  if (OWES.test(text) && !CREDITOR.test(text)) return "owes";
  return "claimant";
}
