// - 새 낱말을 넣으면 lib/reader/dev-cases.ts에 그 표현을 쓴 질문을 더하고, 정답 묶음 채점(accuracy.test.ts)이 떨어지지 않는지 본다.
import type { SectionLabel } from "@/lib/procedure/sections";

export type Section = Exclude<SectionLabel, "none">;
/** w가 음수면 그 섹션이 아닐 가능성을 나타내는 신호다 (예: 매매 하자인데 임대차 낱말이 있음) */
export type Signal = { re: RegExp; w: 1 | 2 | 3 | -2 | -3 };

/** 공백·문장부호·홀로 쓴 자모(ㅋㅋ·ㅠㅠ·ㅇㅇ)를 빼고 NFKC·소문자로 맞춘다 */
export function normText(s: string): string {
  return s
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[ᄀ-ᇿ㄰-㆏]+/g, "")
    .replace(/[\s.,!?~·…"'“”‘’()[\]{}<>:;/\\|*^_+=-]+/g, "");
}

const s = (re: RegExp, w: Signal["w"]): Signal => ({ re, w });

