function step(
  key: string,
  label: string,
  difficulty: Difficulty,
  prepare: string[],
  cautions: string[],
  links: OfficialLink[],
  question: string,
  shortcut?: OfficialLink,
): ProcedureStep {
  return {
    key,
    label,
    difficulty,
    prepare,
    cautions,
    links,
    question,
    ...(shortcut && { shortcut }),
  };
}

