import type { AssistantId } from "./agents";

export type LawRef = { lawName: string; articleNo: string };

type Base = {
  id: string;
  assistant: AssistantId;
  /** 직접 쓴 제목 */
  title: string;
  /** 직접 쓴 사실관계 (이름·주소·금액 없음) */
  situation: string[];
  /** 무엇이 문제였나 */
  issue: string;
  laws: LawRef[];
  /** 대화에서 이 사례의 판례를 근거로 더할지 고르는 낱말 (질문에 하나라도 있으면) */
  keywords: string[];
};

export type PrecedentCase = Base & {
  kind: "precedent";
  /** 법제처 판례 일련번호 (/cases/{precId}) */
  precId: string;
  caseNo: string;
  court: string;
  /** 선고일 YYYY-MM-DD */
  decidedAt: string;
  /** 법원 판단을 직접 다시 쓴 요지 (판결문 인용 아님) */
  holding: string;
};

export type FictionalCase = Base & {
  kind: "fictional";
  /** 이런 절차를 생각해 볼 수 있어요 (결과는 쓰지 않는다) */
  steps: string[];
};

