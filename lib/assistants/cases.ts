export function casesOf(id: AssistantId): AssistantCase[] {
  return ASSISTANT_CASES.filter((c) => c.assistant === id);
}

/**
 * 대화 근거 보강: 질문에 사례 낱말이 들어 있는 공개 판례를 앞에서부터 고른다 (최대 max).
 * 고른 판례는 서버가 그 요청에서 법제처로 다시 가져와 근거 모음에 넣는다 — 저장된 문장을 근거로 쓰지 않는다.
 */
export function pinnedPrecedents(id: AssistantId, maskedText: string, max = 2): PrecedentCase[] {
  const text = maskedText.replace(/\s+/g, " ");
  return casesOf(id)
    .filter((c): c is PrecedentCase => c.kind === "precedent")
    .filter((c) => c.keywords.some((k) => text.includes(k)))
    .slice(0, max);
}
